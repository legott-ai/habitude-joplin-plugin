'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const root = __dirname;
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
assert.equal(pkg.name, 'joplin-plugin-habitude');
assert.equal(pkg.version, manifest.version);
assert.ok(pkg.keywords.includes('joplin-plugin'));
assert.ok(pkg.files.includes('publish'));
const entries = fs.readdirSync(path.join(root, 'publish')).sort();
assert.deepEqual(entries, [`${manifest.id}.jpl`, `${manifest.id}.json`].sort());
const archive = path.join(root, 'publish', `${manifest.id}.jpl`);
const bytes = fs.readFileSync(archive);
assert.deepEqual(bytes, fs.readFileSync(path.join(root, 'dist', `habitude-joplin-${manifest.version}.jpl`)));
const metadata = JSON.parse(fs.readFileSync(path.join(root, 'publish', `${manifest.id}.json`), 'utf8'));
const { _publish_hash, _publish_commit, ...copiedManifest } = metadata;
assert.deepEqual(copiedManifest, manifest);
const hash = crypto.createHash('sha256').update(bytes).digest('hex');
assert.equal(_publish_hash, `sha256:${hash}`);
assert.ok(_publish_commit === '' || /^[^:\s]+:[a-f0-9]{40}$/.test(_publish_commit));
execFileSync('python3', ['-c', 'import tarfile,pathlib,sys,json\nr=pathlib.Path(sys.argv[1]);a=tarfile.open(sys.argv[2]);members=a.getmembers()\nassert sorted(n.name for n in members)==sorted(["index.js","manifest.json","package.json","README.md","LICENSE"])\nfor n in members:\n assert n.isfile() and not pathlib.PurePosixPath(n.name).is_absolute() and ".." not in pathlib.PurePosixPath(n.name).parts\n assert a.extractfile(n).read()==(r/n.name).read_bytes()\nassert json.loads(a.extractfile("package.json").read())["version"]==json.loads(a.extractfile("manifest.json").read())["version"]', root, archive]);
console.log(JSON.stringify({ registryPackageVerified: true, version: manifest.version, publishPair: entries, sha256: hash }));
